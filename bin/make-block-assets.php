<?php
/**
 * Generate the .asset.php file beside each block's editor script.
 *
 * block.json's `editorScript` is registered by core through
 * register_block_script_handle(), which reads dependencies from an
 * `index.asset.php` sitting next to the script. Without that file the
 * dependency list is empty, and two things follow that nothing reports:
 *
 * 1. The script can run before wp-blocks exists. On a site with another block
 *    plugin it never does, because that plugin loads wp-blocks first — which
 *    is why this survived to 2.7.0 unnoticed. On a clean install every block's
 *    registerBlockType() throws on `undefined` and NO blocks appear in the
 *    editor at all.
 * 2. Core only wires up a block's script translations when wp-i18n is among
 *    the declared dependencies (wp-includes/blocks.php, in
 *    register_block_script_handle). So every __() call in these files has been
 *    untranslatable on every site, however complete the catalogue.
 *
 * A @wordpress/scripts build would emit these files. This plugin deliberately
 * ships source with no build step, so they are generated here instead and
 * checked by bin/validate-config.php, which re-derives them and fails if any
 * is missing or stale.
 *
 * Deliberately no 'version' key: core falls back to block.json's version
 * ($script_asset['version'] ?? $block_version), and bin/bump-version.php
 * already keeps that current. A second copy would be a second thing to forget.
 *
 * Usage:
 *   php bin/make-block-assets.php            # write the files
 *   php bin/make-block-assets.php --check    # exit 1 if any is missing or stale
 *
 * @package ProducerKit
 */

declare( strict_types = 1 );

$root  = dirname( __DIR__ );
$check = in_array( '--check', $argv, true );

/**
 * window.wp.blockEditor -> wp-block-editor. Core's handles are the kebab-case
 * form of the global, so this needs no table to fall out of date.
 */
function pkit_global_to_handle( string $global ): string {
	return 'wp-' . strtolower( (string) preg_replace( '/([a-z0-9])([A-Z])/', '$1-$2', $global ) );
}

/**
 * The script handles one editor script actually reaches for.
 *
 * @return string[]
 */
function pkit_dependencies_for( string $js_path ): array {
	$source = (string) file_get_contents( $js_path );

	preg_match_all( '/window\.wp\.([A-Za-z0-9]+)/', $source, $matches );

	$handles = array_map( 'pkit_global_to_handle', array_unique( $matches[1] ) );

	sort( $handles );

	return $handles;
}

$written = [];
$stale   = [];

foreach ( glob( $root . '/blocks/*/block.json' ) ?: [] as $block_json ) {
	$dir      = dirname( $block_json );
	$metadata = json_decode( (string) file_get_contents( $block_json ), true );

	if ( ! isset( $metadata['editorScript'] ) ) {
		continue;
	}

	$script = preg_replace( '/^file:\.?\/?/', '', (string) $metadata['editorScript'] );
	$js     = $dir . '/' . $script;

	if ( ! file_exists( $js ) ) {
		fwrite( STDERR, "Error: {$block_json} names {$script}, which does not exist.\n" );
		exit( 1 );
	}

	$deps  = pkit_dependencies_for( $js );
	$asset = $dir . '/' . substr_replace( $script, '.asset.php', - strlen( '.js' ) );

	$body = "<?php\n"
		. "/**\n"
		. " * Generated by bin/make-block-assets.php — do not edit by hand.\n"
		. " *\n"
		. " * Dependencies are derived from the window.wp.* globals "
		. basename( $js ) . " uses.\n"
		. " * No version key: core falls back to block.json's, which\n"
		. " * bin/bump-version.php keeps current.\n"
		. " */\n\n"
		. "return array(\n"
		. "\t'dependencies' => array(\n";

	foreach ( $deps as $dep ) {
		$body .= "\t\t'" . $dep . "',\n";
	}

	$body .= "\t),\n);\n";

	$current = file_exists( $asset ) ? (string) file_get_contents( $asset ) : '';

	if ( $current === $body ) {
		continue;
	}

	if ( $check ) {
		$stale[] = str_replace( $root . '/', '', $asset ) . ( '' === $current ? ' (missing)' : ' (stale)' );
		continue;
	}

	file_put_contents( $asset, $body );
	$written[] = str_replace( $root . '/', '', $asset ) . '  [' . implode( ', ', $deps ) . ']';
}

if ( $check ) {
	if ( $stale ) {
		fwrite( STDERR, "Block asset files are missing or out of date:\n" );
		foreach ( $stale as $s ) {
			fwrite( STDERR, "  - {$s}\n" );
		}
		fwrite( STDERR, "Run: php bin/make-block-assets.php\n" );
		exit( 1 );
	}

	echo "Block asset files are up to date.\n";
	exit( 0 );
}

if ( ! $written ) {
	echo "Block asset files already up to date.\n";
	exit( 0 );
}

echo "Wrote " . count( $written ) . " block asset file(s):\n";
foreach ( $written as $w ) {
	echo "  {$w}\n";
}
